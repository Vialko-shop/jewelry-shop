const ON_ORDER = new Set(['ring-06', 'br-03', 'set-02']);
const SOLD = new Set(['pd-05']);

export const DEMO_PRODUCTS: ExtendedProduct[] = SEEDS.map(
  ([slug, nameUa, category, material, price, description, badges, extra], i) => {
    const id = `${DEMO_PREFIX}${slug}`;
    const status = extra?.status ?? (SOLD.has(slug) ? 'sold' : ON_ORDER.has(slug) ? 'on_order' : 'in_stock');
    return {
      id,
      name: nameUa,
      nameUa,
      price,
      material,
      category,
      description,
      image: `/demo/${slug}-a.webp`,
      image2: `/demo/${slug}-b.webp`,
      inStock: status !== 'sold',
      weight: extra?.weight,
      size: extra?.size,
      status,
      badges: badges.length ? badges : undefined,
      sortOrder: 100 + i,
    };
  },
);

